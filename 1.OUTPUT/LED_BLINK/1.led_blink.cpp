#include<stm32f10x.h>
int delay(uint32_t a)
{
	while(a--);
}
int main()
{
	RCC->CR=0X00000083;
	RCC->CFGR=0X00000000;
	RCC->APB2ENR=0X0000001C;
	GPIOA->CRL=0X22222222;
	GPIOA->CRH=0X22222222;
	GPIOB->CRL=0X22222222;
	GPIOB->CRH=0X22222222;
	GPIOC->CRH=0X22200000;
	while(1)
	{
		GPIOA->ODR=0X0000FFFF;
		GPIOB->ODR=0X0000FFFF;
		GPIOC->ODR=0X0000E000;
		delay(100000);
		GPIOA->BRR=0X0000FFFF;
		GPIOB->BRR=0X0000FFFF;
		GPIOC->BRR=0X0000E000;
		delay(100000);
	}
}
